/**
 * GET /api/reports/generated/[id]/download
 *
 * Streams a previously generated report (.docx) from the private
 * `generated-reports` Supabase Storage bucket.
 *
 * This route was referenced by the generate route's response
 * (`downloadUrl: /api/reports/generated/<id>/download`) and by the student
 * weekly-logs page's "Word" button, but was never implemented — downloads
 * previously 404'd even when generation succeeded.
 *
 * Security:
 *   - The caller must be authenticated.
 *   - Authorization relies on the `generated_reports` table's SELECT RLS
 *     policy (gen_reports_select_policy), which allows:
 *       * the student the report belongs to
 *       * the user who generated it
 *       * their university admin / program / department coordinators
 *       * super_admin
 *     If the RLS-filtered SELECT returns no row, the caller gets a 404.
 *   - The file bytes are fetched from storage with the SERVICE-ROLE client
 *     because the bucket's storage RLS only lets the UPLOADER read an
 *     object — a student downloading a report generated by their supervisor
 *     would be denied with a user-scoped client even though the report row
 *     itself is visible. Row-level authorization already happened above.
 */

import { NextRequest, NextResponse } from "next/server";
import { createClient } from "@/utils/supabase/server";
import { createClient as createServiceRoleClient } from "@supabase/supabase-js";

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id: reportId } = await params;
    if (!reportId) {
      return NextResponse.json(
        { success: false, error: "Missing report id" },
        { status: 400 }
      );
    }

    const supabase = await createClient();
    const {
      data: { user },
      error: authError,
    } = await supabase.auth.getUser();
    if (!user || authError) {
      return NextResponse.json(
        { success: false, error: "Unauthorized" },
        { status: 401 }
      );
    }

    // 1. Fetch the report row. RLS (gen_reports_select_policy) filters this
    //    SELECT — unauthorized callers receive no row and we 404 without
    //    leaking the report's existence.
    const { data: report, error: reportErr } = await supabase
      .from("generated_reports")
      .select("id, storage_path, filename, mime_type, file_size_bytes, status")
      .eq("id", reportId)
      .maybeSingle();

    if (reportErr || !report) {
      return NextResponse.json(
        { success: false, error: "Report not found or access denied" },
        { status: 404 }
      );
    }

    if (report.status !== "completed") {
      return NextResponse.json(
        { success: false, error: "Report is not ready for download" },
        { status: 409 }
      );
    }

    // 2. Download the object from the private bucket with the service-role
    //    client (server-side privileged read — see the security note above).
    const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
    const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
    if (!url || !serviceKey) {
      return NextResponse.json(
        { success: false, error: "Server storage credentials are not configured" },
        { status: 500 }
      );
    }
    const serviceClient = createServiceRoleClient(url, serviceKey, {
      auth: { persistSession: false, autoRefreshToken: false },
    });

    const { data: fileData, error: downloadErr } = await serviceClient.storage
      .from("generated-reports")
      .download(report.storage_path);

    if (downloadErr || !fileData) {
      console.error("[/api/reports/generated/[id]/download] storage error:", downloadErr);
      return NextResponse.json(
        { success: false, error: "Failed to retrieve the report file" },
        { status: 500 }
      );
    }

    const buffer = Buffer.from(await fileData.arrayBuffer());

    // 3. Stream the .docx back with a download-friendly filename.
    const filename = report.filename || "weekly-report.docx";
    return new NextResponse(new Uint8Array(buffer), {
      status: 200,
      headers: {
        "Content-Type":
          report.mime_type ||
          "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        "Content-Disposition": `attachment; filename="${filename.replace(/"/g, "")}"`,
        "Content-Length": String(buffer.length),
        "Cache-Control": "private, no-store",
      },
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : "Internal server error";
    console.error("[/api/reports/generated/[id]/download] error:", err);
    return NextResponse.json(
      { success: false, error: msg },
      { status: 500 }
    );
  }
}
